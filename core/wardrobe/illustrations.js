export function cutFor(item) {
 const id = item.assets?.thumbnail?.id?.replace(/^thumbnail:/, '') || item.id?.replace(/^closet-/, '');
 const match = /^tpl-([a-z]+)-([1-5])$/.exec(id || '');
 if (!match || match[1] !== item.category) return null;
 const drawing = drawings[match[1]]?.[Number(match[2]) - 1];
 return drawing ? {id, drawing} : null;
}

export function garmentPortrait(item) {
 const cut = cutFor(item);
 if (!cut) return '';
 const [outline, seams] = cut.drawing;
 const color = /^#[0-9a-f]{6}$/i.test(item.color) ? item.color : '#647d69';
 const [shine, weave, opacity] = fabricFinish(item.materialId);
 const tile = patternTile(item.patternId);
 const key = 'fabric-' + String(item.id).replace(/[^\w-]/g, '');
 const p = item.parameters || {};
 const wide = p.width === 'wide' ? 1.10 : p.width === 'slim' ? .91 : 1;
 const long = p.length === 'long' ? 1.08 : p.length === 'short' ? .87 : 1;
 const layer = (paint, alpha) => '<path d="'+outline+'" fill-rule="evenodd" fill="url(#'+key+'-'+paint+')" opacity="'+alpha+'"/>';
 return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-17 0 134 120" data-garment-id="${cut.id}" data-garment-category="${item.category}" role="img">
 <defs>
  <linearGradient id="${key}-light" x1="0" y1=".2" x2=".96" y2=".35"><stop stop-color="${color}"/><stop offset=".24" stop-color="white" stop-opacity="${shine}"/><stop offset=".47" stop-color="${color}"/><stop offset=".76" stop-color="#18272c" stop-opacity=".34"/><stop offset="1" stop-color="${color}"/></linearGradient>
  <pattern id="${key}-print" width="10" height="10" patternUnits="userSpaceOnUse">${tile}</pattern>
  <pattern id="${key}-weave" width="3.2" height="3.2" viewBox="0 0 10 10" patternUnits="userSpaceOnUse">${weave}</pattern>
 </defs>
 <rect x="-17" width="134" height="120" rx="8" fill="#edf1e9"/>
 <ellipse cx="50" cy="112" rx="29" ry="2" fill="#abb9ab" opacity=".23"/>
 <g transform="translate(50 60) scale(${wide} ${long}) translate(-50 -60)" stroke-linejoin="round" stroke-linecap="round">
  <path data-garment="${String(item.id).replace(/[^\w-]/g,'')}" data-region="main" d="${outline}" fill-rule="evenodd" fill="${color}" stroke="#33433d" stroke-width="1.15"/>
  ${layer('light',1)}${weave ? layer('weave',opacity) : ''}${tile ? layer('print',.45) : ''}
  <path d="${seams}" fill="none" stroke="#263b32" opacity=".65" stroke-width="1.05"/>
  <path d="${seams}" transform="translate(.45 .65)" fill="none" stroke="#fff" opacity=".32" stroke-width=".55"/>
 </g></svg>`.replace(/\n\s*/g,'');
}

